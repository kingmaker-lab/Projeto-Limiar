local world = require("engine").new()
world:add_npc("a")
world:add_npc("b")
world:add_mission("quest", "a", 1)
assert(not pcall(world.schedule, world, 0, "b", "quest", "start"))
world:schedule(2, "a", "quest", "start")
world:schedule(2, "a", "quest", "progress")
world:schedule(2, "a", "quest", "cancel")
assert(#world:advance(1) == 0)
local events = world:advance(2)
assert(events[1].status == "active" and events[2].status == "completed")
assert(not events[3].applied and #world:advance(4) == 0)
assert(not pcall(world.advance, world, 2))
